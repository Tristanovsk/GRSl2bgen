    ('/d/S2B_MSIL2A_20200411T110619_N0500_R137_T30TWR_20230509T002033_V2.2.1',
     'S2B_MSIL2B_20200411T110619_N0500_R137_T30TWR_20230509T002033_V2.2.1.nc'),
